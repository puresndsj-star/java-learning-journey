package com.base.datatype;

public class DataTypeDemo1 {
    public static void main(String[] args) {
        //八大基本数据类型
        //整型
        int num1=10;
        byte num2=10;
        short num4=10;
        long num3=10;//long类型，需要在数字后面加L或l，表示这是一个长整型数字
        //浮点型
        float num5=10.0f;//float类型，需要在数字后面加F或f，表示这是一个单精度浮点型数字
        double num6=10.0;
        //字符型
        char num7='国';
        //字符串，String不是关键字，是类
        String num8="中国";
        //布尔型：true或false
        boolean num9=true;
        boolean num10=false;
    }
}
